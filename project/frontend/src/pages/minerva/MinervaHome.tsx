const MermaidChatRenderer: React.FC<{ chart: string }> = ({ chart }) => {
  const [svgHtml, setSvgHtml] = useState<string>('');
  const [error, setError] = useState<boolean>(false);

  useEffect(() => {
    setError(false);
    const id = `mermaid-chat-${Math.floor(Math.random() * 100000)}`;
    
    const renderDiagram = async () => {
      try {
        // Step 1: Pre-validate syntax. If invalid, this throws and bypasses render!
        await mermaid.parse(chart);
        const { svg } = await mermaid.render(id, chart);
        setSvgHtml(svg);
      } catch (err) {
        console.warn('Mermaid rendering validation in chat caught error:', err);
        setError(true);
        // Step 2: Immediate DOM cleanup of any stray containers generated by Mermaid
        const stray = document.getElementById(id);
        if (stray) stray.remove();
        
        // Step 3: Remove any leftover error tooltip divs added to the body
        const strays = document.querySelectorAll('.mermaidTooltip, [id^="d3-"], [id^="mermaid-"]');
        strays.forEach((el) => {
          if (el && !el.querySelector('svg')) {
            el.remove();
          }
        });
      }
    };

    renderDiagram();
  }, [chart]);

  if (error) {
    return (
      <pre className="p-3 bg-zinc-950/80 rounded-xl border border-zinc-800 font-mono text-[10px] text-zinc-400 overflow-x-auto max-w-full my-2">
        {chart}
      </pre>
    );
  }

  return (
    <div className="w-full flex items-center justify-center p-3 my-2 bg-zinc-950/40 border border-white/5 rounded-xl overflow-auto max-h-[300px] scrollbar-thin">
      <div 
        className="w-full max-w-full flex justify-center [&_svg]:max-w-full [&_svg]:h-auto"
        dangerouslySetInnerHTML={{ __html: svgHtml }}
      />
    </div>
  );
};



